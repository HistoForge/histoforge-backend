"""Pure large-region profile and backend execution-plan contracts.

Profiles declare one evidence-backed spatial strategy. Plans are generated by
the backend for one target raster and record recoverable processing units. This
module owns only canonical structure, self-digests, and context-free window
invariants; request/profile/raster agreement belongs to the model-run codec.
"""

from __future__ import annotations

from collections.abc import Iterator, Mapping, Sequence
from typing import Any

from histoforge.canonical_json import (
    canonical_digest,
    canonical_tree,
    require_nonnegative_int32,
    require_positive_int32,
    require_sha256,
)
from histoforge.cloud.execution_limits import fits_target_raster
from histoforge.cloud.sources.identity import validate_int_rect

_GLOBAL_PROFILE_FIELDS = {
    "type",
    "profile_digest",
    "validation_evidence_digest",
}
_CORE_HALO_PROFILE_FIELDS = {
    "type",
    "core_width_px",
    "core_height_px",
    "halo_px",
    "profile_digest",
    "validation_evidence_digest",
}
_WINDOW_FIELDS = {"unit_id", "core_rect", "input_rect"}
_FINITE_PLAN_FIELDS = {"type", "preprocessing_context_digest", "plan_digest"}
_GLOBAL_PLAN_FIELDS = {
    "type",
    "profile_digest",
    "preprocessing_context_digest",
    "plan_digest",
}
_CORE_HALO_PLAN_FIELDS = {
    "type",
    "profile_digest",
    "preprocessing_context_digest",
    "resolved_halo_px",
    "windows",
    "plan_digest",
}
_MAX_INT32 = 2**31 - 1


def build_global_decode_profile(validation_evidence_digest: Any) -> dict[str, Any]:
    """Build the self-digested profile for one whole-raster global decode."""

    preimage = {
        "type": "global-decode",
        "validation_evidence_digest": require_sha256(
            validation_evidence_digest, "validation_evidence_digest"
        ),
    }
    return canonical_tree({**preimage, "profile_digest": canonical_digest(preimage)})


def build_core_halo_profile(
    core_width_px: Any,
    core_height_px: Any,
    halo_px: Any,
    validation_evidence_digest: Any,
) -> dict[str, Any]:
    """Build the self-digested profile for fixed nonoverlapping cores and halo."""

    preimage = {
        "type": "core-halo",
        "core_width_px": require_positive_int32(core_width_px, "core_width_px"),
        "core_height_px": require_positive_int32(core_height_px, "core_height_px"),
        "halo_px": require_nonnegative_int32(halo_px, "halo_px"),
        "validation_evidence_digest": require_sha256(
            validation_evidence_digest, "validation_evidence_digest"
        ),
    }
    return canonical_tree({**preimage, "profile_digest": canonical_digest(preimage)})


def validate_large_region_profile(value: Any) -> dict[str, Any]:
    """Validate one closed self-digested large-region strategy."""

    profile = _require_object(value, "large-region profile")
    profile_type = profile.get("type")
    if profile_type == "global-decode":
        _require_fields(profile, _GLOBAL_PROFILE_FIELDS, "global-decode profile")
        expected = build_global_decode_profile(profile["validation_evidence_digest"])
    elif profile_type == "core-halo":
        _require_fields(profile, _CORE_HALO_PROFILE_FIELDS, "core-halo profile")
        expected = build_core_halo_profile(
            profile["core_width_px"],
            profile["core_height_px"],
            profile["halo_px"],
            profile["validation_evidence_digest"],
        )
    else:
        raise ValueError(f"unsupported large-region profile type: {profile_type!r}")

    digest = require_sha256(profile["profile_digest"], "profile_digest")
    if digest != expected["profile_digest"]:
        raise ValueError("profile_digest does not match profile fields")
    return expected


def validate_processing_window(value: Any) -> dict[str, Any]:
    """Validate one backend-generated core and its containing decode input."""

    window = _require_exact_object(value, _WINDOW_FIELDS, "processing window")
    core = validate_int_rect(window["core_rect"])
    supplied = validate_int_rect(window["input_rect"])
    _require_rect_end_in_int32(core, "core_rect")
    _require_rect_end_in_int32(supplied, "input_rect")
    if not _contains(supplied, core):
        raise ValueError("input_rect must contain core_rect")
    return canonical_tree(
        {
            "unit_id": require_nonnegative_int32(window["unit_id"], "unit_id"),
            "core_rect": core,
            "input_rect": supplied,
        }
    )


def build_finite_plan(preprocessing_context_digest: Any) -> dict[str, Any]:
    """Build the one-unit durable plan with finite-call semantics."""

    preimage = {
        "type": "finite",
        "preprocessing_context_digest": require_sha256(
            preprocessing_context_digest, "preprocessing_context_digest"
        ),
    }
    return canonical_tree({**preimage, "plan_digest": canonical_digest(preimage)})


def build_global_decode_plan(
    profile_digest: Any, preprocessing_context_digest: Any
) -> dict[str, Any]:
    """Build the one-unit plan whose dense fields decode once globally."""

    preimage = {
        "type": "global-decode",
        "profile_digest": require_sha256(profile_digest, "profile_digest"),
        "preprocessing_context_digest": require_sha256(
            preprocessing_context_digest, "preprocessing_context_digest"
        ),
    }
    return canonical_tree({**preimage, "plan_digest": canonical_digest(preimage)})


def build_core_halo_plan(
    profile_digest: Any,
    preprocessing_context_digest: Any,
    windows: Sequence[Any],
    *,
    resolved_halo_px: Any,
) -> dict[str, Any]:
    """Build one self-digested complete fixed-core plan."""

    normalized = _normalize_windows(windows)
    preimage = {
        "type": "core-halo",
        "profile_digest": require_sha256(profile_digest, "profile_digest"),
        "preprocessing_context_digest": require_sha256(
            preprocessing_context_digest, "preprocessing_context_digest"
        ),
        "windows": normalized,
        # Clipped windows can coincide for distinct halos; retain the chosen value.
        "resolved_halo_px": require_nonnegative_int32(
            resolved_halo_px, "resolved_halo_px"
        ),
    }
    return canonical_tree({**preimage, "plan_digest": canonical_digest(preimage)})


def validate_model_execution_plan(value: Any) -> dict[str, Any]:
    """Validate one closed backend-generated self-digested execution plan."""

    plan = _require_object(value, "model execution plan")
    plan_type = plan.get("type")
    if plan_type == "finite":
        _require_fields(plan, _FINITE_PLAN_FIELDS, "finite plan")
        expected = build_finite_plan(plan["preprocessing_context_digest"])
    elif plan_type == "global-decode":
        _require_fields(plan, _GLOBAL_PLAN_FIELDS, "global-decode plan")
        expected = build_global_decode_plan(
            plan["profile_digest"], plan["preprocessing_context_digest"]
        )
    elif plan_type == "core-halo":
        _require_fields(plan, _CORE_HALO_PLAN_FIELDS, "core-halo plan")
        expected = build_core_halo_plan(
            plan["profile_digest"],
            plan["preprocessing_context_digest"],
            plan["windows"],
            resolved_halo_px=plan["resolved_halo_px"],
        )
    else:
        raise ValueError(f"unsupported model execution plan type: {plan_type!r}")

    digest = require_sha256(plan["plan_digest"], "plan_digest")
    if digest != expected["plan_digest"]:
        raise ValueError("plan_digest does not match plan fields")
    return expected


def model_execution_plan_unit_count(
    expected_profile: Any | None, raster: Mapping[str, Any]
) -> int:
    """Return the deterministic processing-unit count for one target raster."""

    width = require_positive_int32(raster.get("width"), "raster.width")
    height = require_positive_int32(raster.get("height"), "raster.height")
    if expected_profile is None:
        return 1
    profile = validate_large_region_profile(expected_profile)
    if profile["type"] == "global-decode":
        return 1
    columns = (width + profile["core_width_px"] - 1) // profile["core_width_px"]
    rows = (height + profile["core_height_px"] - 1) // profile["core_height_px"]
    count = columns * rows
    if count > _MAX_INT32:
        raise ValueError("generated processing-unit count exceeds signed 32-bit range")
    return count


def build_expected_model_execution_plan(
    expected_profile: Any | None,
    raster: Mapping[str, Any],
    preprocessing_context_digest: Any,
    max_units: Any,
    *,
    halo_px_override: Any | None = None,
) -> dict[str, Any]:
    """Derive the exact backend plan for one admitted logical input."""

    unit_limit = require_positive_int32(max_units, "max_units")
    unit_count = model_execution_plan_unit_count(expected_profile, raster)
    if unit_count > unit_limit:
        raise ValueError("generated model execution plan exceeds max_units")
    preprocessing_digest = require_sha256(
        preprocessing_context_digest, "preprocessing_context_digest"
    )
    if halo_px_override is not None:
        halo_px_override = require_nonnegative_int32(
            halo_px_override, "halo_px_override"
        )
        if expected_profile is None or expected_profile.get("type") != "core-halo":
            raise ValueError("halo_px_override requires a core-halo profile")
    if expected_profile is None:
        return build_finite_plan(preprocessing_digest)

    profile = validate_large_region_profile(expected_profile)
    if profile["type"] == "global-decode":
        return build_global_decode_plan(profile["profile_digest"], preprocessing_digest)

    halo = profile["halo_px"] if halo_px_override is None else halo_px_override
    return build_core_halo_plan(
        profile["profile_digest"],
        preprocessing_digest,
        list(_core_halo_windows(profile, raster, halo)),
        resolved_halo_px=halo,
    )


def validate_processing_raster_limits(
    expected_profile: Mapping[str, Any] | None,
    raster: Mapping[str, Any],
    processing_limits: Any,
    *,
    halo_px_override: int | None = None,
) -> None:
    """Check actual allocations after the request and its unit count are admitted.

    Core/halo admission uses the same clipped windows as plan generation. Iteration
    avoids constructing or hashing a second complete plan before source access.
    """

    if expected_profile is None or expected_profile["type"] == "global-decode":
        if not fits_target_raster(raster, processing_limits):
            raise ValueError("model run processing raster exceeds processing_raster")
        return
    halo = expected_profile["halo_px"] if halo_px_override is None else halo_px_override
    for window in _core_halo_windows(expected_profile, raster, halo):
        if not fits_target_raster(window["input_rect"], processing_limits):
            raise ValueError("model run processing window exceeds processing_raster")


def _core_halo_windows(
    profile: Mapping[str, Any], raster: Mapping[str, Any], halo: int
) -> Iterator[dict[str, Any]]:
    """Yield the exact row-major core grid and clipped expanded input rectangles."""

    width = raster["width"]
    height = raster["height"]
    core_width = profile["core_width_px"]
    core_height = profile["core_height_px"]
    unit_id = 0
    for y in range(0, height, core_height):
        clipped_height = min(core_height, height - y)
        for x in range(0, width, core_width):
            clipped_width = min(core_width, width - x)
            input_x = max(0, x - halo)
            input_y = max(0, y - halo)
            input_end_x = min(width, x + clipped_width + halo)
            input_end_y = min(height, y + clipped_height + halo)
            yield {
                "unit_id": unit_id,
                "core_rect": {
                    "x": x,
                    "y": y,
                    "width": clipped_width,
                    "height": clipped_height,
                },
                "input_rect": {
                    "x": input_x,
                    "y": input_y,
                    "width": input_end_x - input_x,
                    "height": input_end_y - input_y,
                },
            }
            unit_id += 1


def _normalize_windows(value: Any) -> list[dict[str, Any]]:
    if not isinstance(value, (list, tuple)) or not value:
        raise ValueError("windows must be a nonempty array")
    windows = [validate_processing_window(window) for window in value]
    unit_ids = [window["unit_id"] for window in windows]
    if unit_ids != list(range(len(windows))):
        raise ValueError("windows must use contiguous unit_id order starting at zero")
    _require_complete_core_cover(windows)
    return windows


def _require_complete_core_cover(windows: list[dict[str, Any]]) -> None:
    rows: dict[int, tuple[int, list[dict[str, int]]]] = {}
    target_width = 0
    target_height = 0
    for window in windows:
        core = window["core_rect"]
        target_width = max(target_width, core["x"] + core["width"])
        target_height = max(target_height, core["y"] + core["height"])
        row = rows.get(core["y"])
        if row is None:
            rows[core["y"]] = (core["height"], [core])
        else:
            height, cores = row
            if height != core["height"]:
                raise ValueError("cores sharing a row must have the same height")
            cores.append(core)

    expected_columns: list[tuple[int, int]] | None = None
    canonical_cores: list[dict[str, int]] = []
    next_y = 0
    for row_y in sorted(rows):
        row_height, cores = rows[row_y]
        if row_y != next_y:
            raise ValueError("core rectangles must cover rows without gaps or overlap")
        next_x = 0
        sorted_cores = sorted(cores, key=lambda rectangle: rectangle["x"])
        columns = [(core["x"], core["width"]) for core in sorted_cores]
        if expected_columns is None:
            expected_columns = columns
        elif columns != expected_columns:
            raise ValueError("every core row must use the same column partition")
        for core in sorted_cores:
            if core["x"] != next_x:
                raise ValueError(
                    "core rectangles must cover columns without gaps or overlap"
                )
            next_x += core["width"]
        if next_x != target_width:
            raise ValueError("every core row must cover the same target width")
        canonical_cores.extend(sorted_cores)
        next_y += row_height
    if next_y != target_height:
        raise ValueError("core rectangles must cover the target height")
    if [window["core_rect"] for window in windows] != canonical_cores:
        raise ValueError("windows must be ordered row-major by core_rect")

    for window in windows:
        supplied = window["input_rect"]
        if (
            supplied["x"] + supplied["width"] > target_width
            or supplied["y"] + supplied["height"] > target_height
        ):
            raise ValueError("input_rect must stay inside the logical target rectangle")


def _contains(outer: Mapping[str, int], inner: Mapping[str, int]) -> bool:
    return (
        outer["x"] <= inner["x"]
        and outer["y"] <= inner["y"]
        and outer["x"] + outer["width"] >= inner["x"] + inner["width"]
        and outer["y"] + outer["height"] >= inner["y"] + inner["height"]
    )


def _require_rect_end_in_int32(rectangle: Mapping[str, int], path: str) -> None:
    if (
        rectangle["x"] + rectangle["width"] > _MAX_INT32
        or rectangle["y"] + rectangle["height"] > _MAX_INT32
    ):
        raise ValueError(f"{path} endpoint must fit a signed 32-bit target raster")


def _require_object(value: Any, path: str) -> Mapping[str, Any]:
    if not isinstance(value, dict):
        raise ValueError(f"{path} must be an object")
    return value


def _require_exact_object(value: Any, fields: set[str], path: str) -> Mapping[str, Any]:
    result = _require_object(value, path)
    _require_fields(result, fields, path)
    return result


def _require_fields(value: Mapping[str, Any], fields: set[str], path: str) -> None:
    actual = set(value)
    if actual != fields:
        raise ValueError(
            f"{path} fields mismatch: "
            f"missing={sorted(fields - actual)}, unknown={sorted(actual - fields)}"
        )
